"""Master resumes. Each lives in profile/resumes/<id>/:

  master_resume.docx   the person's resume: layout, fonts, fixed sections, refined bullets
  resume.yaml          {description: which roles this resume targets, default: true|false}
  layout.yaml          optional: section headings the template builder should recognize
  template.docx/.json  generated by `jobpipe build-template`

Code that needs "the" resume asks for `active()`. A job is processed inside `use(resume)`;
outside of that the default resume is active.
"""

from __future__ import annotations

import contextvars
from contextlib import contextmanager
from dataclasses import dataclass
from functools import cached_property
from pathlib import Path
from typing import Any, Iterator

import yaml

from jobpipe.config import path


@dataclass(frozen=True)
class Resume:
    id: str
    dir: Path

    @property
    def master(self) -> Path:
        return self.dir / "master_resume.docx"

    @property
    def template(self) -> Path:
        return self.dir / "template.docx"

    @property
    def meta_file(self) -> Path:
        return self.dir / "template.json"

    @cached_property
    def info(self) -> dict[str, Any]:
        f = self.dir / "resume.yaml"
        return (yaml.safe_load(f.read_text(encoding="utf-8")) or {}) if f.exists() else {}

    @cached_property
    def layout(self) -> dict[str, Any]:
        f = self.dir / "layout.yaml"
        return (yaml.safe_load(f.read_text(encoding="utf-8")) or {}) if f.exists() else {}

    @property
    def description(self) -> str:
        return " ".join(str(self.info.get("description", "")).split())


class NoResume(Exception):
    pass


def all_resumes() -> list[Resume]:
    root = path("resumes")
    if not root.exists():
        return []
    return [Resume(d.name, d) for d in sorted(root.iterdir()) if (d / "master_resume.docx").exists()]


def get(resume_id: str) -> Resume:
    for r in all_resumes():
        if r.id == resume_id:
            return r
    known = ", ".join(r.id for r in all_resumes()) or "none"
    raise NoResume(f"no resume {resume_id!r} in {path('resumes')} (have: {known})")


def default() -> Resume:
    resumes = all_resumes()
    if not resumes:
        raise NoResume(f"no master resume found: put one at {path('resumes')}/<id>/master_resume.docx")
    return next((r for r in resumes if r.info.get("default")), resumes[0])


def choose(suggested: str = "", forced: str | None = None) -> Resume:
    """The resume to use for a job: the forced one, else the LLM's suggestion if it names a
    real resume, else the default."""
    if forced:
        return get(forced)
    for r in all_resumes():
        if suggested and r.id == suggested.strip():
            return r
    return default()


_active: contextvars.ContextVar[Resume | None] = contextvars.ContextVar("active_resume", default=None)


def active() -> Resume:
    return _active.get() or default()


@contextmanager
def use(r: Resume) -> Iterator[Resume]:
    token = _active.set(r)
    try:
        yield r
    finally:
        _active.reset(token)
